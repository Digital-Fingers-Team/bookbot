import { Schema, model, type InferSchemaType } from "mongoose";

/**
 * What an admin account may do. Admin is no longer all-or-nothing: one account
 * can answer support and nothing else, another can publish books but never open
 * a reader's record. `admins` is the meta-permission — it lets an account
 * create other admins and decide what each of them may reach.
 */
export const ADMIN_PERMISSIONS = [
  "books",
  "requests",
  "users",
  "organizations",
  "support",
  "feedback",
  "analytics",
  "admins"
] as const;

export type AdminPermission = (typeof ADMIN_PERMISSIONS)[number];

const userSchema = new Schema(
  {
    name: { type: String, required: true, trim: true, maxlength: 120 },
    email: { type: String, required: true, unique: true, lowercase: true, trim: true, index: true },
    passwordHash: { type: String, required: true, select: false },
    role: { type: String, enum: ["admin", "org_admin", "user"], required: true, default: "user" },
    // Which admin tools this account may use. Only meaningful for role "admin".
    // The field is deliberately left absent rather than defaulted to []: an
    // absent field marks an account created before permissions existed, which
    // backfillAdminPermissions() grants the full set exactly once. An admin
    // deliberately restricted to an empty list keeps the empty list.
    adminPermissions: { type: [String], enum: ADMIN_PERMISSIONS, default: undefined },
    language: { type: String, enum: ["en", "ar"], required: true, default: "en" },
    // --- Access control (admin-granted) ---
    // A user may read / ask the AI about a book only if its id is in
    // allowedBookIds OR its category is in allowedCategories. Admins bypass
    // this entirely. Granted by an admin after a paid access request, or by
    // an org_admin (scoped to their organization's subscribed catalog).
    allowedBookIds: { type: [Schema.Types.ObjectId], ref: "Book", default: [] },
    allowedCategories: { type: [String], default: [] },
    // --- Organization membership (universities etc.) ---
    // Set for students belonging to a subscribing organization, and for the
    // org_admin(s) who manage them. Just membership — it does not grant
    // access by itself; an org_admin still grants each student's books
    // individually from the organization's catalog.
    organizationId: { type: Schema.Types.ObjectId, ref: "Organization" },
    // Downloading the raw PDF is a separate, narrower grant than read access:
    // a book must be in allowedBookIds AND here before its file can be
    // downloaded. Defaults closed — admins opt users in book by book.
    allowedDownloadBookIds: { type: [Schema.Types.ObjectId], ref: "Book", default: [] },
    // --- OMP (Open Monograph Press) author link ---
    // Set once the user activates an author account in OMP. The OMP password is
    // generated by us, stored encrypted (never plaintext), and used for SSO login.
    ompUserId: { type: Number },
    ompUsername: { type: String, trim: true },
    ompPasswordEnc: { type: String, select: false },
    ompLinkedAt: { type: Date }
  },
  { timestamps: { createdAt: true, updatedAt: false } }
);

export type UserRole = "admin" | "org_admin" | "user";
export type UserDocument = InferSchemaType<typeof userSchema> & {
  _id: unknown;
  role: UserRole;
};

/** Keep only values that are still real permissions (stale rows, bad input). */
export function normalizeAdminPermissions(value: unknown): AdminPermission[] {
  if (!Array.isArray(value)) {
    return [];
  }
  return ADMIN_PERMISSIONS.filter((permission) => value.includes(permission));
}

userSchema.index({ organizationId: 1 });

export const User = model("User", userSchema);
